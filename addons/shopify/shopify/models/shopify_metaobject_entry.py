    def action_delete_from_shopify(self):
        """Task: T9096 - Remove this entry from Shopify (if it was ever pushed) and then from Odoo."""
        self.ensure_one()
        mk_instance = self.mk_instance_id
        mk_log_line_dict = {'error': [], 'success': []}
        if not mk_instance.enable_metaobject:
            # Show the same "turned off" message as a popup instead of leaving only a log line.
            self.delete_from_shopify(mk_log_line_dict=mk_log_line_dict)
            raise MarketplaceException(mk_log_line_dict['error'][0]['log_message'])
        mk_log_id = self.env['mk.log'].create_update_log(mk_instance_id=mk_instance, operation_type='export')
        is_deleted = self.delete_from_shopify(mk_log_line_dict=mk_log_line_dict)
        self.env['mk.log'].create_update_log(mk_log_id=mk_log_id, mk_instance_id=mk_instance,
                                             operation_type='export', mk_log_line_dict=mk_log_line_dict)
        if not mk_log_id.log_line_ids:
            mk_log_id.unlink()

        if is_deleted:
            action = self.env['ir.actions.act_window']._for_xml_id('shopify.action_shopify_metaobject_entries')
            return action
        return True

    def delete_from_shopify(self, mk_log_line_dict=None):
        """Task: T9096 - Delete this entry in Shopify, when it has one, then remove the Odoo record.

        The reference check runs BEFORE the Shopify call, not after: deleting in Shopify
        and then finding the local unlink blocked would leave Odoo pointing at a Shopify id
        that no longer exists.

        Args:
            mk_log_line_dict (dict, optional): Dictionary to collect log messages.
        Returns:
            bool: True once removed from Shopify (if applicable) and from Odoo.
        """
        self.ensure_one()
        if mk_log_line_dict is None:
            mk_log_line_dict = {'error': [], 'success': []}
        # Read before the record is deleted: the success line below is written after unlink().
        log_vals = {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                    'instance': self.mk_instance_id.name}

        if not self.mk_instance_id.enable_metaobject:
            mk_log_line_dict['error'].append({'log_message': _(
                "UPDATE METAOBJECT ENTRY: Cannot delete entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                "Reason: Metaobject Functionality is turned off for this instance\n"
                "How to fix:\n"
                "  • Go to Marketplaces > Configuration > Instance, open the instance, go to the Metafields tab, and turn on Metaobject Functionality."
            ) % log_vals})
            return False

        if not self.definition_id.is_app_writable:
            mk_log_line_dict['error'].append({'log_message': _(
                "UPDATE METAOBJECT ENTRY: Cannot delete entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                "Reason: Shopify only lets Shopify staff delete entries of this metaobject\n"
                "How to fix:\n"
                "  • Delete the entry in Shopify admin (Content > Metaobjects), then go to Marketplaces > Shopify > Catalogs > Metaobjects, open the metaobject and click Fetch Entries"
            ) % log_vals})
            return False

        usages = self._is_shopify_entry_referenced(with_usages=True)
        if usages:
            mk_log_line_dict['error'].append({'log_message': _(
                "UPDATE METAOBJECT ENTRY: Cannot delete entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                "Reason: it is still used by these records:\n"
                "%(usages)s\n"
                "How to fix:\n"
                "  • Open each record above (a product: Marketplaces > Products > Products, tab Shopify Metaobject Fields), remove the entry, then delete it again"
            ) % {**log_vals, 'usages': "\n".join(f"  • {usage}" for usage in usages)}})
            return False

        if self.mk_id:
            mk_instance_id = self.mk_instance_id
            mk_instance_id.connection_to_shopify()
            res = mk_instance_id.execute_graphql_query(
                DELETE_METAOBJECT, variables={"id": f"gid://shopify/Metaobject/{self.mk_id}"})
            result = ((res or {}).get('data') or {}).get('metaobjectDelete') or {}
            user_errors = result.get('userErrors') or []
            if user_errors:
                for error in user_errors:
                    mk_log_line_dict['error'].append({'log_message': _(
                        "UPDATE METAOBJECT ENTRY: Shopify rejected deleting entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                        "Reason: %(message)s (code: %(code)s)"
                    ) % {**log_vals, 'message': error.get('message'), 'code': error.get('code')}})
                return False

        try:
            self.unlink()
        except MarketplaceException as e:
            mk_log_line_dict['error'].append({'log_message': exception_message(e)})
            return False

        mk_log_line_dict['success'].append({'log_message': _(
            "UPDATE METAOBJECT ENTRY: Entry %(entry)s (%(definition)s) was deleted from Shopify and Odoo for instance (%(instance)s)"
        ) % log_vals})
        return True
