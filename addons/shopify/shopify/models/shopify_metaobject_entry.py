def _build_shopify_metaobjects_batch_query(count, first):
    """Task: T9096 - Assemble METAOBJECTS_BATCH_QUERY for a batch of `count` types.
    Only the assembly lives here - one alias per type, joined together - the GraphQL text
    itself (METAOBJECTS_BATCH_QUERY, METAOBJECT_BATCH_ALIAS) is in graphql_queries.py with
    every other query and mutation.
    Args:
        count (int): Number of types in this batch.
        first (int): Page size per type.
    Returns:
        str: The query document, with $type0..$type{count-1} to fill in as variables.
    """
    var_decls = ', '.join(f"$type{i}: String!" for i in range(count))
    aliases = "\n".join(METAOBJECT_BATCH_ALIAS % {'index': i, 'first': first} for i in range(count))
    return METAOBJECTS_BATCH_QUERY % {'var_decls': var_decls, 'aliases': aliases}


class ShopifyMetaobjectEntry(models.Model):
    """One Shopify metaobject entry (a "filled-in form").

    This is the model that product/variant/order/customer metaobject-reference
    metafields point at. It is the only metaobject model Odoo may create or
    write back to Shopify.
    """
    _name = 'shopify.metaobject.entry.ts'
    _description = 'Shopify Metaobject Entry'
    _order = 'definition_id, display_name_ts'
    _rec_name = 'display_name_ts'

    mk_instance_id = fields.Many2one('mk.instance', string="Instance", required=True, ondelete='cascade',
                                     help="Marketplace instance this entry belongs to.")
    definition_id = fields.Many2one('shopify.metaobject.definition.ts', string="Metaobject", required=True,
                                    ondelete='cascade', domain="[('mk_instance_id', '=', mk_instance_id)]",
                                    help="Metaobject definition this entry is an instance of.")
    shopify_type = fields.Char(related='definition_id.shopify_type', store=True, string="Type")
    is_app_writable = fields.Boolean(related='definition_id.is_app_writable', store=True,
                                     string="Writable by Apps")

    mk_id = fields.Char(string="Shopify ID", index=True, copy=False,
                        help="Numeric part of the Shopify Metaobject GID. Empty until the entry is pushed to Shopify. "
                             "This is the identity used to match entries, never the handle.")
    handle = fields.Char(string="Handle", copy=False,
                         help="Shopify handle of the entry. Generated by Shopify when omitted on create. "
                              "Used as the write key for metaobjectUpsert.")
    display_name_ts = fields.Char(string="Shopify Display Name", readonly=True, copy=False,
                                  help="Value of the definition's display name field. Computed by Shopify from the "
                                       "field named in the definition, so it is filled in on import or on push.")

    value_ids = fields.One2many('shopify.metaobject.entry.value.ts', 'entry_id', string="Values", copy=True,
                                help="One row per field of the definition.")

    _uniq_entry_per_instance = models.Constraint(
        "UNIQUE(mk_instance_id, definition_id, mk_id)",
        "This metaobject entry already exists for this instance.")

    def _shopify_entry_label(self):
        """Task: T9096 - Readable name for logs: Shopify display name, else handle, else the Odoo id."""
        self.ensure_one()
        return self.display_name_ts or self.handle or str(self.id)

    def _is_shopify_entry_referenced(self, with_usages=False):
        """Task: T9096 - True when some other Odoo record still points at this entry.

        Checks both the auto-created product/customer/... fields (see
        shopify.metafield.mapping.ts._create_shopify_metaobject_odoo_field) and nested
        metaobject_reference values held on other entries. Used to keep a manual or
        auto-cleanup delete from silently breaking a link the merchant still relies on.
        With with_usages=True it returns where the entry is used (first 5 per place, as
        readable text, empty when unused) instead of a bool, for log messages.
        """
        self.ensure_one()
        limit = 5 if with_usages else 1
        usages = []
        manual_fields = self.env['ir.model.fields'].sudo().search([
            ('relation', '=', self._name), ('state', '=', 'manual')])
        for field in manual_fields:
            model = self.env.get(field.model)
            if model is None or field.name not in model._fields:
                continue
            domain = [(field.name, 'in', self.ids)] if field.ttype == 'many2many' else [(field.name, '=', self.id)]
            records = model.sudo().search(domain, limit=limit)
            if records and not with_usages:
                return True
            usages += [f"{field.model_id.name}: {record.display_name}" for record in records]

        values = self.env['shopify.metaobject.entry.value.ts'].sudo().search(
            ['|', ('val_entry_id', '=', self.id), ('val_entry_ids', 'in', self.id)], limit=limit)
        if not with_usages:
            return bool(values)
        return usages + [_("Metaobject entry: %s") % value.entry_id._shopify_entry_label() for value in values]

    @api.model_create_multi
    def create(self, vals_list):
        """Task: T9096 - No entry can be added for an instance that has metaobjects turned off.

        Covers every way of adding one: Add Entry, New inside an entry picker, imports.
        """
        instances = self.env['mk.instance'].browse(
            [vals.get('mk_instance_id') or self.env.context.get('default_mk_instance_id') for vals in vals_list])
        disabled = instances.filtered(lambda instance: not instance.enable_metaobject)
        if disabled:
            raise MarketplaceException(_(
                "UPDATE METAOBJECT ENTRY: Cannot add an entry for instance (%(instance)s)\n"
                "Reason: Metaobject Functionality is turned off for this instance\n"
                "How to fix:\n"
                "  • Go to Marketplaces > Configuration > Instance, open the instance, go to the Metafields tab, and turn on Metaobject Functionality."
            ) % {'instance': ', '.join(disabled.mapped('name'))})
        return super().create(vals_list)

    def unlink(self):
        """Task: T9096 - Block removing an entry that something else in Odoo still points at.

        Applies to every deletion path - the standard list/form delete, the auto-cleanup
        below, and action_delete_from_shopify - since they all end up calling this.
        """
        for entry in self:
            usages = entry._is_shopify_entry_referenced(with_usages=True)
            if usages:
                raise MarketplaceException(_(
                    "SHOPIFY METAOBJECT: Cannot remove entry %(entry)s (%(definition)s)\n"
                    "Reason: it is still used by these records:\n"
                    "%(usages)s\n"
                    "How to fix:\n"
                    "  • Remove the entry from these records, then remove it again"
                ) % {'entry': entry._shopify_entry_label(), 'definition': entry.definition_id.name,
                     'usages': "\n".join(f"  • {usage}" for usage in usages)})
        return super().unlink()

    @api.onchange('definition_id')
    def _onchange_shopify_definition_id(self):
        """Task: T9096 - Generate one blank value row per field of the chosen definition."""
        for record in self:
            if not record.definition_id:
                record.value_ids = [Command.clear()]
                continue
            record.value_ids = [Command.clear()] + [
                Command.create({'field_id': field.id}) for field in record.definition_id.field_ids
            ]

