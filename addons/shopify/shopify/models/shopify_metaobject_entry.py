    def handle_deleted_in_shopify(self, mk_log_line_dict=None, owner_label='listing', mk_record=None, metafield_key=''):
        """Task: T9096 - Handle metaobject entries in Odoo when deleted in Shopify."""
        record_name = mk_record.display_name if mk_record else ''
        record_mk_id = mk_record.mk_id if mk_record else ''

        for entry in self:
            entry_label = entry._shopify_entry_label()
            log_vals = {'entry': entry_label, 'definition': entry.definition_id.name, 'metafield': metafield_key,
                        'owner_label': owner_label, 'record_name': record_name, 'record_mk_id': record_mk_id}
            try:
                # Bypass the manual block and force the database deletion
                entry.with_context(force_shopify_delete=True).unlink()

                if mk_log_line_dict is not None:
                    mk_log_line_dict['success'].append({'log_message': _(
                        "UPDATE LISTING: Metafield %(metafield)s on %(owner_label)s %(record_name)s (%(record_mk_id)s) was not updated\n"
                        "Reason: its entry %(entry)s (%(definition)s) was deleted in Shopify, so Odoo removed it\n"
                        "How to fix:\n"
                        "  • Run the update again"
                    ) % log_vals})
            except Exception:
                # Tell the user exactly which metafield on which product has the stale data
                if mk_log_line_dict is not None:
                    mk_log_line_dict['error'].append({'log_message': _(
                        "UPDATE LISTING: Metafield %(metafield)s on %(owner_label)s %(record_name)s (%(record_mk_id)s) was not updated\n"
                        "Reason: its entry %(entry)s (%(definition)s) was deleted in Shopify, but it is still selected in Odoo\n"
                        "How to fix:\n"
                        "  • Remove %(entry)s from %(metafield)s: open the product of this %(owner_label)s (Marketplaces > Products > Products), go to the Shopify Metaobject Fields tab, then run the update again"
                    ) % log_vals})

    def action_push_to_shopify(self):
        """Task: T9096 - Create or update this entry in Shopify."""
        self.ensure_one()
        mk_log_line_dict = {'error': [], 'success': []}
        if not self.mk_instance_id.enable_metaobject:
            # Show the same "turned off" message as a popup instead of leaving only a log line.
            self.push_to_shopify(mk_log_line_dict=mk_log_line_dict)
            raise MarketplaceException(mk_log_line_dict['error'][0]['log_message'])
        mk_log_id = self.env['mk.log'].create_update_log(mk_instance_id=self.mk_instance_id, operation_type='export')
        self.push_to_shopify(mk_log_line_dict=mk_log_line_dict)
        self.env['mk.log'].create_update_log(mk_log_id=mk_log_id, mk_instance_id=self.mk_instance_id,
                                             operation_type='export', mk_log_line_dict=mk_log_line_dict)
        if not mk_log_id.log_line_ids:
            mk_log_id.unlink()
        return True

    def push_to_shopify(self, mk_log_line_dict=None):
        """Task: T9096 - Push the entry to Shopify, creating it when it has no Shopify id yet.

        Args:
            mk_log_line_dict (dict, optional): Dictionary to collect log messages.
        Returns:
            bool: True when Shopify accepted the write.
        """
        self.ensure_one()
        if mk_log_line_dict is None:
            mk_log_line_dict = {'error': [], 'success': []}

        if not self.mk_instance_id.enable_metaobject:
            mk_log_line_dict['error'].append({'log_message': _(
                "EXPORT METAOBJECT ENTRY: Cannot sync entry %(entry)s (%(definition)s) to Shopify for instance (%(instance)s)\n"
                "Reason: Metaobject Functionality is turned off for this instance\n"
                "How to fix:\n"
                "  • Go to Marketplaces > Configuration > Instance, open the instance, go to the Metafields tab, and turn on Metaobject Functionality."
            ) % {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                 'instance': self.mk_instance_id.name}})
            return False

        if not self.definition_id.is_app_writable:
            mk_log_line_dict['error'].append({'log_message': _(
                "EXPORT METAOBJECT ENTRY: Cannot sync entry %(entry)s (%(definition)s) to Shopify for instance (%(instance)s)\n"
                "Reason: Shopify only lets Shopify staff add or change entries of this metaobject\n"
                "How to fix:\n"
                "  • Add or change the entry in Shopify admin (Content > Metaobjects), then go to Marketplaces > Shopify > Catalogs > Metaobjects, open the metaobject and click Fetch Entries"
            ) % {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                 'instance': self.mk_instance_id.name}})
            return False

        mk_instance_id = self.mk_instance_id
        mk_instance_id.connection_to_shopify()
        payload_fields = self._prepare_shopify_metaobject_fields_payload(mk_log_line_dict)
        if not payload_fields:
            mk_log_line_dict['error'].append({'log_message': _(
                "EXPORT METAOBJECT ENTRY: Nothing synced for entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                "Reason: every field is empty or links to records that are not synced to Shopify yet\n"
                "How to fix:\n"
                "  • Go to Marketplaces > Shopify > Catalogs > Metaobject Entries, open the entry, fill in a value in the Values tab and sync the linked records, then click Sync to Shopify"
            ) % {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                 'instance': mk_instance_id.name}})
            return False

        if self.mk_id:
            query = UPDATE_METAOBJECT
            variables = {"id": f"gid://shopify/Metaobject/{self.mk_id}",
                         "metaobject": {"fields": payload_fields}}
            result_key = 'metaobjectUpdate'
        else:
            metaobject_input = {"type": self.definition_id.shopify_type, "fields": payload_fields}
            if self.handle:
                metaobject_input['handle'] = self.handle
            query = CREATE_METAOBJECT
            variables = {"metaobject": metaobject_input}
            result_key = 'metaobjectCreate'

        res = mk_instance_id.execute_graphql_query(query, variables=variables)
        result = ((res or {}).get('data') or {}).get(result_key) or {}
        user_errors = result.get('userErrors') or []

        # metafieldsSet drops the rejected entries and re-issues the mutation once
        # (_update_shopify_metafield_values). Do the same so one bad field does not cost
        # the whole entry.
        if user_errors:
            failed_indices = {idx for idx in (self._shopify_field_error_index(e) for e in user_errors)
                              if idx is not None and idx < len(payload_fields)}
            if failed_indices:
                for index in sorted(failed_indices):
                    error = next((e for e in user_errors if self._shopify_field_error_index(e) == index), {})
                    field_key = payload_fields[index].get('key')
                    field_name = self.definition_id.field_ids.filtered(lambda f: f.key == field_key)[:1].name or field_key
                    mk_log_line_dict['error'].append({'log_message': _(
                        "EXPORT METAOBJECT ENTRY: Shopify rejected the value of field %(field)s of entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                        "Reason: %(message)s (code: %(code)s), the other values were synced\n"
                        "How to fix:\n"
                        "  • Go to Marketplaces > Shopify > Catalogs > Metaobject Entries, open the entry, correct %(field)s in the Values tab, then click Sync to Shopify"
                    ) % {'field': field_name, 'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                         'instance': mk_instance_id.name, 'message': error.get('message'), 'code': error.get('code')}})
                cleaned = [f for i, f in enumerate(payload_fields) if i not in failed_indices]
                if cleaned:
                    variables['metaobject'] = dict(variables['metaobject'], fields=cleaned)
                    res = mk_instance_id.execute_graphql_query(query, variables=variables)
                    result = ((res or {}).get('data') or {}).get(result_key) or {}
                    user_errors = result.get('userErrors') or []
                else:
                    user_errors = []
                    result = {}

        if user_errors:
            for error in user_errors:
                mk_log_line_dict['error'].append({'log_message': _(
                    "EXPORT METAOBJECT ENTRY: Shopify rejected entry %(entry)s (%(definition)s) for instance (%(instance)s)\n"
                    "Reason: %(message)s (field: %(field)s, code: %(code)s)"
                ) % {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
                     'instance': mk_instance_id.name, 'message': error.get('message'),
                     'field': error.get('field'), 'code': error.get('code')}})
            return False

        metaobject = result.get('metaobject') or {}
        if metaobject:
            self.write({
                'mk_id': str(extract_numeric_id(metaobject.get('id'))),
                'handle': metaobject.get('handle'),
                'display_name_ts': metaobject.get('displayName') or self.display_name_ts,
            })
        mk_log_line_dict['success'].append({'log_message': _(
            "EXPORT METAOBJECT ENTRY: Entry %(entry)s (%(definition)s) was synced to Shopify for instance (%(instance)s)"
        ) % {'entry': self._shopify_entry_label(), 'definition': self.definition_id.name,
             'instance': mk_instance_id.name}})
        return True

    def _shopify_field_error_index(self, error):
        """Task: T9096 - Index into the fields list that a Shopify userError points at, or None.

        Shopify returns paths such as ['metaobject', 'fields', '2', 'value'].
        """
        for part in error.get('field') or []:
            if isinstance(part, str) and part.isdigit():
                return int(part)
            if isinstance(part, int):
                return part
        return None

    def _prepare_shopify_metaobject_fields_payload(self, mk_log_line_dict=None):
        """Task: T9096 - Build the `fields` list for metaobjectCreate / metaobjectUpdate.

        A field whose references are not in Shopify yet is SKIPPED and the reason logged,
        so the rest of the entry still exports. This mirrors how metafields behave in
        prepare_shopify_reference_value_for_update. Because Shopify patches the entry,
        a skipped field simply keeps its current Shopify value instead of being cleared.

        Args:
            mk_log_line_dict (dict, optional): Dictionary to collect log messages.
        Returns:
            list: [{'key': str, 'value': str}, ...]
        """
        self.ensure_one()
        payload = []
        for value_record in self.value_ids:
            if not value_record.key:
                continue
            # Never send a type the connector cannot convert: omitting it from a patch
            # update leaves the merchant's Shopify value exactly as it was.
            if not value_record.is_supported:
                continue
            skip_reason = value_record._export_skip_reason()
            if skip_reason:
                if mk_log_line_dict is not None:
                    mk_log_line_dict['error'].append({'log_message': skip_reason})
                continue
            shopify_value = value_record._to_shopify_value(mk_log_line_dict=mk_log_line_dict)
            payload.append({'key': value_record.key, 'value': '' if shopify_value in (False, None) else shopify_value})
        return payload

